import { createServer } from 'node:http'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

function jsonAssignment(source, marker, closing) {
  const start = source.indexOf(marker)
  if (start < 0) throw new Error(`Could not find generated assignment: ${marker}`)
  const valueStart = start + marker.length
  const valueEnd = source.lastIndexOf(closing) + closing.length
  return JSON.parse(source.slice(valueStart, valueEnd))
}

const echoSource = await readFile(path.join(root, 'src/game-data/echoes.generated.ts'), 'utf8')
const sonataSource = await readFile(path.join(root, 'src/game-data/sonatas.generated.ts'), 'utf8')
const echoes = jsonAssignment(echoSource, 'export const generatedEchoCatalog:GeneratedEchoCatalogEntry[]=', ']')
  .filter((entry) => entry.iconSourceUrl)
  .map(({ name, cost, iconSourceUrl }) => ({ name, cost, url: iconSourceUrl }))
const sonataMarker = 'export const generatedSonataIconSources:Record<string,string>='
const sonatas = Object.entries(jsonAssignment(sonataSource, sonataMarker, '}')).map(([name, url]) => ({ name, url }))

const html = `<!doctype html><meta charset="utf-8"><title>Generating scanner signatures</title>
<style>body{font:16px system-ui;background:#101416;color:#eef;padding:24px}progress{width:min(640px,90vw);height:24px}</style>
<h1>Generating local scanner signatures</h1><p id="status">Starting...</p><progress id="progress" value="0" max="${echoes.length + sonatas.length}"></progress>
<script type="module">
const echoes=${JSON.stringify(echoes)};
const sonatas=${JSON.stringify(sonatas)};
const status=document.querySelector('#status'), progress=document.querySelector('#progress');
function signature(image){
  const canvas=document.createElement('canvas'); canvas.width=16; canvas.height=16;
  const context=canvas.getContext('2d',{willReadFrequently:true}); context.drawImage(image,0,0,16,16);
  const pixels=context.getImageData(0,0,16,16).data, values=[];
  for(let offset=0;offset<pixels.length;offset+=4) values.push(pixels[offset+3]<32?0:(pixels[offset]*.2126+pixels[offset+1]*.7152+pixels[offset+2]*.0722)/255);
  const mean=values.reduce((sum,value)=>sum+value,0)/values.length;
  const deviation=Math.sqrt(values.reduce((sum,value)=>sum+(value-mean)**2,0)/values.length)||1;
  return values.map(value=>Math.round(Math.max(-2,Math.min(2,(value-mean)/deviation))*32));
}
async function load(item){
  return new Promise((resolve,reject)=>{const image=new Image();image.crossOrigin='anonymous';image.onload=()=>resolve({...item,signature:signature(image)});image.onerror=()=>reject(new Error('Failed '+item.url));image.src=item.url+'?scanner-signatures=3.6';});
}
async function mapLimit(items,limit){
  const results=new Array(items.length); let next=0,done=0;
  await Promise.all(Array.from({length:limit},async()=>{while(next<items.length){const index=next++;results[index]=await load(items[index]);done++;progress.value=done;status.textContent='Processed '+done+' of '+items.length;}}));
  return results;
}
try{
  const echoResults=await mapLimit(echoes,8);
  progress.max=echoes.length+sonatas.length; progress.value=echoes.length;
  const sonataResults=await mapLimit(sonatas,8); progress.value=progress.max;
  const response=await fetch('/complete',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({echoes:echoResults,sonatas:sonataResults})});
  if(!response.ok) throw new Error(await response.text()); status.textContent='Complete. This tab can close.';
}catch(error){status.textContent=error instanceof Error?error.message:String(error);document.body.dataset.failed='true';}
</script>`

const server = createServer(async (request, response) => {
  if (request.method === 'GET') {
    response.writeHead(200, { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' })
    response.end(html)
    return
  }
  if (request.method === 'POST' && request.url === '/complete') {
    let body = ''
    for await (const chunk of request) body += chunk
    const result = JSON.parse(body)
    const clean = (entry) => ({ name: entry.name, ...('cost' in entry ? { cost: entry.cost } : {}), signature: entry.signature })
    const output = `// Generated by scripts/generate-scanner-signatures.mjs. Do not edit.\nexport const scannerSignatureVersion='3.6'\nexport const generatedEchoSignatures=${JSON.stringify(result.echoes.map(clean))} as const\nexport const generatedSonataSignatures=${JSON.stringify(result.sonatas.map(clean))} as const\n`
    await writeFile(path.join(root, 'src/game-data/scanner-signatures.generated.ts'), output)
    response.writeHead(204); response.end()
    setTimeout(() => server.close(), 50)
    return
  }
  response.writeHead(404); response.end('Not found')
})

server.listen(0, '127.0.0.1', () => {
  const address = server.address()
  if (!address || typeof address === 'string') throw new Error('Could not start the local signature generator.')
  console.log(`Open http://127.0.0.1:${address.port}/ to generate scanner signatures.`)
})
